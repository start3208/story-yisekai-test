// -------------------------------------------------------------
// STANDARD COMPREHENSIVE STORY SYNTHESIZER (~420-520 chars)
// -------------------------------------------------------------
export function synthesizeRichStory(
  trans: TransmigrationId,
  cheat: CheatId,
  identity: IdentityId,
  genre: GenreId,
  race?: RaceId
): { storyText: string; epilogueQuote: string } {
  // 1. Act 1: Origin
  const originPart = TRANS_ORIGIN_PROSE[trans];

  // 2. Act 2: Cheat + Race (for peasant)
  const cheatPart = CHEAT_MECHANICS_PROSE[cheat];
  const racePart = identity === 'peasant' && race ? PEASANT_RACE_PROSE[race] : '';

  // 3. Act 3: Climax Resolution & Quote
  const key = `${identity}_${genre}`;
  const resolution = CLIMAX_RESOLUTIONS[key] || CLIMAX_RESOLUTIONS.hero_retired;

  // Build fluid cohesive multi-act prose
  const storyText = `${originPart}\n\n${racePart}${cheatPart}\n\n${resolution.scenario}\n\n正如你在异世界巅峰留下的传世名言：“${resolution.quote}”`;

  return {
    storyText,
    epilogueQuote: resolution.quote
  };
}
